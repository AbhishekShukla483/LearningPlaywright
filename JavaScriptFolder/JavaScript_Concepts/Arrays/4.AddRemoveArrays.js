let arr = [1,2,3];
console.log(arr);
//add new elements in array at last 
arr.push(4);
console.log(arr);
//remove elements at last 
arr.pop();
console.log(arr);
//add mutliple elements in array at last array
arr.push(4,5,6);
console.log(arr);
//add new elements at the begining
arr.unshift(0);
console.log(arr);
//remove multiple elements from the begining 
arr.shift();
console.log(arr);

